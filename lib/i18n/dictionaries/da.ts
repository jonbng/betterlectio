/**
 * Widen string literals to `string` so other locales can `satisfies DaDictionary`
 * with their own values, while still preserving the nested key structure for
 * `Path<DaDictionary>` inference. This is the schema; `da` itself is the source
 * of truth for both keys and the default-language strings.
 */
type WidenLeaves<T> = T extends string
  ? string
  : { [K in keyof T]: WidenLeaves<T[K]> };

export type DaDictionary = WidenLeaves<typeof da>;
